"""Шаг 1. Товарные группы из данных задания 1 + синтетическая матрица «страна × доли групп».
В файлах Белстата нет разбивки по странам, поэтому
задания матрица страны × группы генерируется синтетически.
Товарные группы берём из реального списка позиций задания 1 
Запуск:  python src/make_matrix.py
"""
from pathlib import Path
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "source" / "belstat_all.xlsx"
OUT = ROOT / "data" / "processed"

RULES = [  
    ("Фармацевтика", ["лекарств"]),
    ("Автомобили и запчасти", ["легковые", "автомобил"]),
    ("Электроника и связь", ["аппаратура связи", "вычислительные", "провода"]),
    ("Машины и оборудование", ["двигатели", "машины и механические", "сельскохозяйственная техника", "холодильник"]),
    ("Металлы и металлоизделия", ["черные металлы", "трубы", "металлоконструкции"]),
    ("Химия и пластмассы", ["каучук", "химические волокна", "тара пластмассовая"]),
    ("Древесина и мебель", ["лесоматериалы", "плиты древесно", "мебель"]),
    ("Продовольствие и АПК", ["говядина", "масл", "молоко", "мясо", "сахар", "сыры", "отходы"]),
]

GROUPS = ["Продовольствие и АПК", "Металлы и металлоизделия", "Машины и оборудование", "Автомобили и запчасти",
          "Электроника и связь", "Химия и пластмассы", "Древесина и мебель", "Фармацевтика"]
assert set(GROUPS) == {g for g, _ in RULES}


def group_of(name: str) -> str:
    low = name.lower()
    for g, keys in RULES:
        if any(k in low for k in keys):
            return g
    raise ValueError(f"Нет группы для: {name}")


prod = pd.read_excel(SRC)[["Товар", "Поток"]].drop_duplicates()
prod["Товар"] = prod["Товар"].str.replace(r"\s+", " ", regex=True).str.strip()
prod["Группа"] = prod["Товар"].map(group_of)
prod = prod.sort_values(["Группа", "Поток", "Товар"])
prod.to_csv(OUT / "product_groups.csv", index=False, encoding="utf-8-sig")
print(prod.groupby("Группа").size().to_string(), "\n")

#            Прод   Мет   Маш   Авто  Элек  Хим   Древ  Фарм
ARCH = {
    "Соседи СНГ/ЕАЭС":      ([.30, .08, .14, .22, .04, .06, .10, .06],
                             ["Россия", "Казахстан", "Армения", "Кыргызстан", "Узбекистан", "Азербайджан",
                              "Грузия", "Молдова", "Украина", "Туркменистан", "Таджикистан"]),
    "Промышленная Европа":  ([.06, .14, .16, .10, .08, .20, .24, .02],
                             ["Германия", "Польша", "Литва", "Латвия", "Чехия", "Нидерланды", "Италия",
                              "Франция", "Эстония", "Венгрия", "Словакия", "Австрия"]),
    "Азия — техника":       ([.02, .06, .26, .06, .38, .12, .06, .04],
                             ["Китай", "Южная Корея", "Япония", "Вьетнам", "Тайвань", "Малайзия",
                              "Таиланд", "Индия"]),
    "Покупатели продовольствия": ([.62, .04, .05, .03, .02, .14, .05, .05],
                             ["Египет", "Алжир", "Ирак", "Иран", "Бразилия", "Аргентина", "Индонезия",
                              "Саудовская Аравия", "ОАЭ", "Ливия"]),
}
rng = np.random.default_rng(42)
rows, names, arch = [], [], []
for label, (mean, countries) in ARCH.items():
    for c in countries:
        rows.append(rng.dirichlet(np.array(mean) * 40))  
        names.append(c); arch.append(label)

# два намеренных «выброса» 
rows.append(rng.dirichlet(np.array([.02, .70, .08, .02, .02, .10, .04, .02]) * 60)); names.append("Страна-металлург (синт.)"); arch.append("Выброс")
rows.append(rng.dirichlet(np.array([.03, .03, .04, .03, .03, .05, .74, .05]) * 60)); names.append("Страна-лесоэкспортёр (синт.)"); arch.append("Выброс")

X = pd.DataFrame(rows, index=names, columns=GROUPS)
X.index.name = "Страна"
X.round(4).to_csv(OUT / "country_share_matrix_SYNTHETIC.csv", encoding="utf-8-sig")
pd.Series(arch, index=names, name="заложенный_архетип").to_csv(
    OUT / "country_archetype_SYNTHETIC.csv", encoding="utf-8-sig", index_label="Страна")
print(f"Матрица: {X.shape[0]} стран × {X.shape[1]} групп; суммы строк = {X.sum(axis=1).round(6).unique()}")
